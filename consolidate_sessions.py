"""
Session consolidation: one living "<Topic> Session Log" per project/topic.

projects/ holds hundreds of flat session-*.md notes. Each is assigned to the
topic folder it matches best (same topic vectors as cross_link.py), and that
folder gets a log note with one dated line per session, newest first, linking
the original. Originals are never moved or deleted. The log is fully
regenerated each run, so it is safe to re-run.

    python consolidate_sessions.py            # dry run: counts per topic
    python consolidate_sessions.py --apply
"""
import argparse
import re
from collections import defaultdict
from datetime import date
from pathlib import Path

import numpy as np

import cross_link
from classifier import VAULT_PATH, _add_line_under

MIN_SIM = 0.80          # below this a session has no clear project
SESSIONS = VAULT_PATH / "projects"
FALLBACK = VAULT_PATH / "projects"   # unmatched sessions get a general log here


def _summary(note: Path) -> str:
    """One line: first sentence of the most informative section."""
    text = note.read_text(errors="ignore")
    for heading in ("## What was done", "## Outcome", "## Topic"):
        if heading in text:
            body = text.split(heading, 1)[1].split("\n## ", 1)[0]
            body = re.sub(r"\s+", " ", body.replace("---", " ")).strip(" -")
            if body:
                first = re.split(r"(?<=[.!?])\s", body, 1)[0]
                return first[:160]
    return ""


def _date(note: Path) -> str:
    m = re.search(r"(20\d\d-\d\d-\d\d)", note.name)
    return m.group(1) if m else "undated"


def _log_path(folder: Path) -> Path:
    if folder == FALLBACK:
        return folder / "General Session Log.md"
    return folder / f"{folder.name.replace('-', ' ').title()} Session Log.md"


def assign(only: Path | None = None) -> dict[Path, list[Path]]:
    """topic folder -> session notes that belong to it."""
    notes = cross_link._note_vectors()
    topics = cross_link._topics(notes)
    folders = list(topics)
    mat = np.stack([topics[f][1] for f in folders])
    out: dict[Path, list[Path]] = defaultdict(list)
    for p, v in notes.items():
        if p.parent != SESSIONS or not p.name.startswith("session-"):
            continue
        if only is not None and p != only:
            continue
        sims = mat @ v
        i = int(np.argmax(sims))
        out[folders[i] if sims[i] >= MIN_SIM else FALLBACK].append(p)
    return out


def write_log(folder: Path, sessions: list[Path]) -> Path:
    log = _log_path(folder)
    lines = [f"- **{_date(s)}** [[{s.stem}]] {_summary(s)}".rstrip()
             for s in sorted(sessions, key=lambda s: s.name, reverse=True)]
    moc = cross_link._find_moc(folder)
    up = f"Up: [[{moc.stem}]]\n\n" if moc else ""
    log.write_text(f"""---
topic: {folder.relative_to(VAULT_PATH).parts[0]}
tags:
  - session-log
  - auto-generated
last_updated: {date.today().isoformat()}
---

# {log.stem}

{up}Generated by consolidate_sessions.py: one line per session, newest first.
Re-running rebuilds it, so don't hand-edit below this line.

## Sessions

""" + "\n".join(lines) + "\n")
    if moc:
        _add_line_under(moc, "## Sub-MOCs", f"- [[{log.stem}]]")
    return log


def add_session(note: Path) -> None:
    """Append one new session to its topic log. Called from summarize_session."""
    for folder, sessions in assign(only=note).items():
        log = _log_path(folder)
        if not log.exists():
            write_log(folder, sessions)
            continue
        line = f"- **{_date(note)}** [[{note.stem}]] {_summary(note)}".rstrip()
        text = log.read_text(errors="ignore")
        if f"[[{note.stem}]]" not in text:
            log.write_text(text.replace("## Sessions\n\n", f"## Sessions\n\n{line}\n", 1))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()
    groups = assign()
    print(f"{sum(map(len, groups.values()))} sessions into {len(groups)} logs")
    for folder, s in sorted(groups.items(), key=lambda x: -len(x[1])):
        print(f"  {len(s):4d}  {_log_path(folder).relative_to(VAULT_PATH)}")
    if args.apply:
        for folder, s in groups.items():
            write_log(folder, s)
        print("applied")


if __name__ == "__main__":
    main()
